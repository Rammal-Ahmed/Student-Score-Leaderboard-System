print("=" * 40)
print("STUDENT SCORE LEADERBOARD SYSTEM".center(40))
print("=" * 40)


lines = [
    "Ayesha, 78, 91, 65",
    "  bilal ,100,80",
    "Chen, 88, 90",
    "Dana",
    "Omar, 85, abc",
    "",
]

results = []

for line in lines:
    line = line.strip()

    # Skip empty lines
    if line == "":
        continue

    parts = line.split(",")

    name = parts[0].strip().title()
    scores = parts[1:]

    # Skip lines with no name or no scores
    if name == "" or len(scores) == 0:
        continue

    total = 0
    is_broken = False

    # Validate scores and calculate the total
    for piece in scores:
        piece = piece.strip()

        if piece.isdigit():
            total += int(piece)
        else:
            is_broken = True
            break

    # Skip the entire line if any score is invalid
    if is_broken:
        continue

    average = round(total / len(scores), 1)
    results.append([average, name])

# Sort by average, highest first
results.sort()
results.reverse()

# Print the ranked list
rank = 0

for average, name in results:
    rank += 1
    print(str(rank) + ". " + name + " - " + str(average))